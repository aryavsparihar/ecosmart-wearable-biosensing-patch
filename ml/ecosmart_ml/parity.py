"""Golden vectors proving the C++ firmware and this Python port agree.

A deterministic synthetic recording (plus a burst of random and out-of-range
samples to stress clamping and overflow paths) is run through the Python
pipeline; every window's features, z-scores, decision and alert state are
written to test/test_parity/parity_vectors.h. The native Unity test replays
the same samples through the C++ pipeline and requires an exact match.
"""

from __future__ import annotations

import struct
from typing import List, Tuple

import numpy as np

from . import config as C
from .pipeline import TreeModel, run
from .synth import generate_subject

PARITY_SEED = 10
PARITY_SAMPLES = 480
STRESS_SAMPLES = 64


def model_fingerprint(model: TreeModel) -> int:
    """FNV-1a over the model exactly as laid out in flash (little-endian)."""
    blob = b"".join(struct.pack("<bbBB", *n) for n in model.nodes)
    blob += b"".join(struct.pack("<i", f) for f in model.scale_floors)
    h = 0x811C9DC5
    for byte in blob:
        h = ((h ^ byte) * 0x01000193) & 0xFFFFFFFF
    return h


def parity_samples() -> List[Tuple[int, int, int]]:
    rng = np.random.default_rng(PARITY_SEED)
    subj = generate_subject(rng, 0, n_samples=PARITY_SAMPLES, max_episodes=2,
                            earliest_episode=150)
    samples = list(zip(subj.ph.tolist(), subj.cond.tolist(), subj.temp.tolist()))
    stress = rng.integers(C.SAMPLE_MIN, C.SAMPLE_MAX + 1, size=(STRESS_SAMPLES, 3))
    stress[::7] = [-50, 12000, 32767]  # must be clamped exactly like the firmware
    samples += [tuple(int(v) for v in row) for row in stress]
    return samples


def render_header(model: TreeModel) -> str:
    samples = parity_samples()
    events = run(samples, model=model)
    out = [
        "// AUTO-GENERATED by ml/export_parity_vectors.py - do not edit by hand.",
        "// Expected outputs of the Python pipeline (ml/ecosmart_ml/pipeline.py)",
        "// for the samples below; test_parity requires the C++ pipeline to match.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"#define PARITY_MODEL_FINGERPRINT 0x{model_fingerprint(model):08X}UL",
        f"#define PARITY_NUM_SAMPLES {len(samples)}",
        f"#define PARITY_NUM_WINDOWS {len(events)}",
        "",
        "struct ParityWindow {",
        "  uint16_t endSample;",
        "  uint8_t phase;",
        "  uint8_t classified;",
        f"  int32_t features[{C.NUM_FEATURES}];",
        f"  int8_t z[{C.NUM_FEATURES}];",
        "  uint8_t label;",
        "  uint8_t pAnomaly;",
        "  uint8_t leaf;",
        "  uint8_t alert;",
        "};",
        "",
        "static const int16_t kParitySamples[PARITY_NUM_SAMPLES][3] = {",
    ]
    out += [f"    {{{a}, {b}, {c}}}," for a, b, c in samples]
    out += ["};", "", "static const ParityWindow kParityWindows[PARITY_NUM_WINDOWS] = {"]
    for ev in events:
        z = ev.z if ev.z is not None else [0] * C.NUM_FEATURES
        out.append(
            f"    {{{ev.end_sample}, {ev.phase}, {int(ev.z is not None)}, "
            f"{{{', '.join(map(str, ev.features))}}}, {{{', '.join(map(str, z))}}}, "
            f"{ev.label}, {ev.p_anomaly}, {max(ev.leaf, 0)}, {int(ev.alert)}}},")
    out += ["};", ""]
    return "\n".join(out)
