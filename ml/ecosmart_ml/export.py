"""Conversion of a fitted scikit-learn tree into the firmware's integer form,
and writers for include/model_weights.h and the JSON model snapshot."""

from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Dict, List, Sequence

import numpy as np

from . import config as C
from .pipeline import LEAF, TreeModel


def tree_from_sklearn(clf, X: np.ndarray, y: np.ndarray, floors: Sequence[int]) -> TreeModel:
    """Quantises a fitted DecisionTreeClassifier.

    Features are integer z-scores, so sklearn's split `z <= t.5` is exactly
    `z <= floor(t)`. Leaf probabilities come from the training windows that
    land in each leaf and the leaf label is their majority class. Splits whose
    two subtrees always predict the same label are collapsed into one leaf:
    they change the reported probability but never the decision, so dropping
    them saves flash.
    """
    t = clf.tree_
    leaf_of = clf.apply(X)

    def build(i: int):
        """Returns a nested node: ('leaf', pos, total) or ('split', f, thr, l, r)."""
        if t.children_left[i] == -1:
            in_leaf = y[leaf_of == i]
            return ("leaf", int(in_leaf.sum()), len(in_leaf))
        thr = max(-128, min(127, int(math.floor(t.threshold[i]))))
        left, right = build(t.children_left[i]), build(t.children_right[i])
        if left[0] == right[0] == "leaf" and _label(left) == _label(right):
            return ("leaf", left[1] + right[1], left[2] + right[2])
        return ("split", int(t.feature[i]), thr, left, right)

    nodes: List[tuple] = []

    def emit(n) -> int:
        idx = len(nodes)
        nodes.append(None)
        if n[0] == "leaf":
            _, pos, total = n
            nodes[idx] = (LEAF, 0, int(round(100 * pos / total)) if total else 0, _label(n))
        else:
            _, f, thr, left, right = n
            li = emit(left)
            ri = emit(right)
            nodes[idx] = (f, thr, li, ri)
        return idx

    emit(build(0))
    if len(nodes) > 255:
        raise ValueError("tree too large for uint8 child indices")
    return TreeModel(nodes=nodes, scale_floors=[int(f) for f in floors])


def _label(leaf) -> int:
    _, pos, total = leaf
    return 1 if 2 * pos > total else 0


def tree_depth(model: TreeModel) -> int:
    def depth(i: int) -> int:
        f, _, l, r = model.nodes[i]
        return 0 if f == LEAF else 1 + max(depth(l), depth(r))
    return depth(0)


def _describe(node, index: int) -> str:
    f, thr, l, r = node
    if f == LEAF:
        return f"{index:2d}: leaf -> {'ANOMALY' if r else 'normal'} ({l}% anomalous)"
    return f"{index:2d}: {C.FEATURE_NAMES[f]} <= {thr / C.Z_SCALE:+.2f} sigma ? {l} : {r}"


def write_header(model: TreeModel, path: Path, provenance: Dict[str, object]) -> None:
    lines: List[str] = [
        "// AUTO-GENERATED by ml/train.py - do not edit by hand.",
        "// Regenerate with:  python ml/generate_data.py && python ml/train.py",
        "//",
        "// Decision tree trained on SYNTHETIC data only (see ml/ecosmart_ml/synth.py).",
    ]
    lines += [f"// {k}: {v}" for k, v in provenance.items()]
    lines += [
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        '#include "model_types.h"',
        '#include "platform.h"',
        "",
        f"#define MODEL_NUM_FEATURES {C.NUM_FEATURES}",
        f"#define MODEL_WINDOW_SIZE {C.WINDOW_SIZE}",
        f"#define MODEL_WINDOW_HOP {C.WINDOW_HOP}",
        f"#define MODEL_CALIBRATION_WINDOWS {C.CALIBRATION_WINDOWS}",
        f"#define MODEL_Z_SCALE {C.Z_SCALE}",
        f"#define MODEL_NUM_NODES {len(model.nodes)}",
        f"#define MODEL_MAX_DEPTH {tree_depth(model)}",
        "",
        "// Lower bound on each feature's baseline scale (same units as the feature).",
        "static const int32_t kModelScaleFloor[MODEL_NUM_FEATURES] PROGMEM = {",
    ]
    for name, fl in zip(C.FEATURE_NAMES, model.scale_floors):
        lines.append(f"    {fl:>8d},  // {name}")
    lines += [
        "};",
        "",
        "// {feature, threshold (z * 16), left, right}",
        "static const ModelNode kModelNodes[MODEL_NUM_NODES] PROGMEM = {",
    ]
    for i, node in enumerate(model.nodes):
        f, thr, l, r = node
        lines.append(f"    {{{f:3d}, {thr:4d}, {l:3d}, {r:3d}}},  // {_describe(node, i)}")
    lines += ["};", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines))


def save_model_json(model: TreeModel, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({
        "feature_names": list(C.FEATURE_NAMES),
        "scale_floors": model.scale_floors,
        "nodes": [list(n) for n in model.nodes],
    }, indent=1) + "\n")


def load_model_json(path: Path) -> TreeModel:
    d = json.loads(path.read_text())
    return TreeModel(nodes=[tuple(n) for n in d["nodes"]], scale_floors=d["scale_floors"])
