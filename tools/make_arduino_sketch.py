#!/usr/bin/env python3
"""Assemble an Arduino IDE / arduino-cli sketch from the PlatformIO sources.

    python tools/make_arduino_sketch.py                # -> build/arduino/ecosmart_patch/
    python tools/make_arduino_sketch.py --simulation   # SIMULATION_MODE baked in

The Arduino IDE wants every source file next to <folder>/<folder>.ino, so this
flattens src/, src/hal/ and include/ into one folder (all includes are flat,
e.g. #include "pipeline.h", so nothing needs rewriting). Then:

    Arduino IDE: File > Open > build/arduino/ecosmart_patch/ecosmart_patch.ino,
                 install "OneWire" via the Library Manager, board "Arduino Nano".
    arduino-cli: arduino-cli lib install OneWire
                 arduino-cli compile --fqbn arduino:avr:nano build/arduino/ecosmart_patch
"""

import argparse
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKETCH = "ecosmart_patch"

INO = """// Eco-Smart Wearable Biosensing Patch - Arduino IDE entry point.
//
// GENERATED by tools/make_arduino_sketch.py from the PlatformIO project; edit
// the sources under src/ and include/ in the repository instead.
// setup() and loop() live in main.cpp alongside this file.
//
// Research prototype - NOT a medical device, not for diagnosis.
"""

SIM_DEFINE = "#define SIMULATION_MODE 1  // added by make_arduino_sketch.py --simulation\n"
SIM_FILES = {"main.cpp", "serial_logger.cpp"}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=ROOT / "build" / "arduino")
    ap.add_argument("--simulation", action="store_true",
                    help="compile the on-device synthetic signal generator in")
    args = ap.parse_args()

    dest = args.out / SKETCH
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)

    sources = sorted((ROOT / "include").glob("*.h"))
    sources += sorted((ROOT / "src").rglob("*.cpp"))
    seen = set()
    for src in sources:
        if src.name in seen:
            raise SystemExit(f"duplicate file name {src.name}: cannot flatten")
        seen.add(src.name)
        text = src.read_text()
        if args.simulation and src.name in SIM_FILES:
            text = SIM_DEFINE + text
        (dest / src.name).write_text(text)

    (dest / f"{SKETCH}.ino").write_text(INO)
    mode = " (SIMULATION_MODE)" if args.simulation else ""
    print(f"wrote {len(sources) + 1} files to {dest}{mode}")


if __name__ == "__main__":
    main()
